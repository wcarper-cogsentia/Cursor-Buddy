#include <Arduino.h>
#include "st7701.h"
#include "board.h"
#include "exio.h"

static void write9(uint16_t value) {
  for (int i = 8; i >= 0; --i) {
    digitalWrite(LCD_SCLK_PIN, LOW);
    digitalWrite(LCD_MOSI_PIN, (value >> i) & 1);
    digitalWrite(LCD_SCLK_PIN, HIGH);
  }
  digitalWrite(LCD_SCLK_PIN, LOW);
}

static void cmd(uint8_t c) { write9(c); }
static void dat(uint8_t d) { write9(static_cast<uint16_t>(0x100 | d)); }

static void datN(const uint8_t *data, size_t n) {
  for (size_t i = 0; i < n; ++i) dat(data[i]);
}

bool st7701Init() {
  pinMode(LCD_MOSI_PIN, OUTPUT);
  pinMode(LCD_SCLK_PIN, OUTPUT);
  digitalWrite(LCD_MOSI_PIN, LOW);
  digitalWrite(LCD_SCLK_PIN, LOW);

  exioSet(EXIO_LCD_RST, false);
  delay(10);
  exioSet(EXIO_LCD_RST, true);
  delay(50);

  exioSet(EXIO_LCD_CS, false);
  delay(10);

  cmd(0xFF);
  static const uint8_t b10[] = {0x77, 0x01, 0x00, 0x00, 0x10};
  datN(b10, sizeof(b10));

  cmd(0xC0);
  dat(0x3B);
  dat(0x00);
  cmd(0xC1);
  dat(0x0B);
  dat(0x02);
  cmd(0xC2);
  dat(0x07);
  dat(0x02);
  cmd(0xCC);
  dat(0x10);
  cmd(0xCD);
  dat(0x08);

  cmd(0xB0);
  static const uint8_t b0[] = {
      0x00, 0x11, 0x16, 0x0e, 0x11, 0x06, 0x05, 0x09,
      0x08, 0x21, 0x06, 0x13, 0x10, 0x29, 0x31, 0x18};
  datN(b0, sizeof(b0));
  cmd(0xB1);
  static const uint8_t b1[] = {
      0x00, 0x11, 0x16, 0x0e, 0x11, 0x07, 0x05, 0x09,
      0x09, 0x21, 0x05, 0x13, 0x11, 0x2a, 0x31, 0x18};
  datN(b1, sizeof(b1));

  cmd(0xFF);
  static const uint8_t b11[] = {0x77, 0x01, 0x00, 0x00, 0x11};
  datN(b11, sizeof(b11));
  cmd(0xB0);
  dat(0x6d);
  cmd(0xB1);
  dat(0x37);
  cmd(0xB2);
  dat(0x81);
  cmd(0xB3);
  dat(0x80);
  cmd(0xB5);
  dat(0x43);
  cmd(0xB7);
  dat(0x85);
  cmd(0xB8);
  dat(0x20);
  cmd(0xC1);
  dat(0x78);
  cmd(0xC2);
  dat(0x78);
  cmd(0xD0);
  dat(0x88);
  cmd(0xE0);
  dat(0x00);
  dat(0x00);
  dat(0x02);

  cmd(0xE1);
  static const uint8_t e1[] = {0x03, 0xA0, 0x00, 0x00, 0x04, 0xA0, 0x00, 0x00, 0x00, 0x20, 0x20};
  datN(e1, sizeof(e1));
  cmd(0xE2);
  static const uint8_t e2[] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
  datN(e2, sizeof(e2));
  cmd(0xE3);
  dat(0x00);
  dat(0x00);
  dat(0x11);
  dat(0x00);
  cmd(0xE4);
  dat(0x22);
  dat(0x00);
  cmd(0xE5);
  static const uint8_t e5[] = {
      0x05, 0xEC, 0xA0, 0xA0, 0x07, 0xEE, 0xA0, 0xA0,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
  datN(e5, sizeof(e5));
  cmd(0xE6);
  dat(0x00);
  dat(0x00);
  dat(0x11);
  dat(0x00);
  cmd(0xE7);
  dat(0x22);
  dat(0x00);
  cmd(0xE8);
  static const uint8_t e8[] = {
      0x06, 0xED, 0xA0, 0xA0, 0x08, 0xEF, 0xA0, 0xA0,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
  datN(e8, sizeof(e8));
  cmd(0xEB);
  static const uint8_t eb[] = {0x00, 0x00, 0x40, 0x40, 0x00, 0x00, 0x00};
  datN(eb, sizeof(eb));
  cmd(0xED);
  static const uint8_t ed[] = {
      0xFF, 0xFF, 0xFF, 0xBA, 0x0A, 0xBF, 0x45, 0xFF,
      0xFF, 0x54, 0xFB, 0xA0, 0xAB, 0xFF, 0xFF, 0xFF};
  datN(ed, sizeof(ed));
  cmd(0xEF);
  static const uint8_t ef[] = {0x10, 0x0D, 0x04, 0x08, 0x3F, 0x1F};
  datN(ef, sizeof(ef));

  cmd(0xFF);
  static const uint8_t b13[] = {0x77, 0x01, 0x00, 0x00, 0x13};
  datN(b13, sizeof(b13));
  cmd(0xEF);
  dat(0x08);

  cmd(0xFF);
  static const uint8_t b00[] = {0x77, 0x01, 0x00, 0x00, 0x00};
  datN(b00, sizeof(b00));
  cmd(0x36);
  dat(0x00);
  cmd(0x3A);
  dat(0x66);  // Waveshare official: RGB666 on the 16-bit bus (R0/B0 are NC)
  cmd(0x11);
  delay(480);
  cmd(0x20);
  delay(120);
  cmd(0x29);

  exioSet(EXIO_LCD_CS, true);
  delay(10);
  Serial.println("[st7701] command init done");
  return true;
}

void st7701SleepIn() {
  exioSet(EXIO_LCD_CS, false);
  delay(10);
  cmd(0x28);
  delay(20);
  cmd(0x10);
  delay(120);
  exioSet(EXIO_LCD_CS, true);
}
